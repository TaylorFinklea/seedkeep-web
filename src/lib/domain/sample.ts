const I = (
	sci: string,
	life: string,
	sun: string,
	frost: string,
	sow: string,
	depth: number | null,
	germ: Range | null,
	mat: Range | null,
	soil: Range | null,
	spacing: number | null,
	row: number | null,
	viability: number | null,
	instr: string
): SeedInfo => ({
	sci,
	life,
	sun,
	frost,
	sow,
	depth,
	germ,
	mat,
	soil,
	spacing,
	row,
	viability,
	instr
});

const S = (
	id: string,
	name: string,
	variety: string,
	company: string,
	type: string,
	state: SeedState,
	packets: number,
	year: number | null,
	loc: string,
	tags: string[],
	verdict: Verdict | null,
	window: [YMD, YMD] | null,
	info: SeedInfo | null,
	notes?: string
): Seed => ({
	id,
	name,
	variety,
	company,
	type,
	state,
	packets,
	year,
	loc,
	tags,
	verdict,
	window,
	info,
	notes: notes || '',
	catalog: !!verdict,
	version: 1,
	catalogId: verdict ? `cat_${id}` : null,
	source: 'store'
});

const E = (
	id: string,
	bed: string,
	seed: string,
	kind: PlantingEvent['kind'],
	date: YMD,
	done: boolean,
	x: number,
	y: number,
	notes?: string
): PlantingEvent => ({ id, bed, seed, kind, date, done, x, y, notes: notes || '', version: 1 });

